"""Render typed TRIM requests to ASCII native inputs; expose no execution effects."""

from agentic_srim.capabilities.trim.inputs import Request


def number(value: float) -> str:
    """Return a native-compatible decimal from a finite numeric input."""
    return format(value, ".12g")


def render(request: Request) -> str:
    """Return CRLF TRIM.IN for request, with no plots or interactive reminders.

    Native lengths are Angstroms (10 per nm). Unused Bragg flag is zero;
    autosave is bounded at 32000 and does not change the requested ion count.
    """
    output = request.outputs
    lines = ["==> SRIM TRIM input generated by agentic_srim",
             "Ion: Z1, M1, Energy (keV), Angle, Number, Bragg Corr, AutoSave Number",
             f"{request.ion_atomic_number} {number(request.ion_mass_u)} {number(request.energy_keV)} {number(request.angle_degrees)} {request.ion_count} 0 {min(request.ion_count, 32000)}",
             "Cascades (1..8), Random Number Seed, Reminders",
             f"{request.calculation_mode} {request.random_seed} 0",
             "Diskfiles: Ranges, Backscatt, Transmit, Sputtered, Collisions, EXYZ interval eV",
             f"{int(output.ranges)} {int(output.backscatter)} {int(output.transmit)} {int(output.sputter)} {output.collisions} {output.exyz_interval_eV}",
             "Target material: Number of Elements & Layers",
             f'"{request.title}" {len(request.elements)} {len(request.layers)}',
             "PlotType (5=no plots); Plot Depths: Xmin, Xmax (Angstrom)",
             f"5 {number(request.depth_min_nm * 10)} {number(request.depth_max_nm * 10)}",
             "Target Elements: Z Mass(amu)"]
    for index, element in enumerate(request.elements, 1):
        prefix = f"Atom {index:02d} = X ="
        lines.append(f"{prefix:<16}{element.atomic_number} {number(element.mass_u)}")
    lines.extend(["Layer Layer Name Width Density Stoichiometry", "Numb Description (Angstrom) (g/cm3) Atomic amounts"])
    for index, layer in enumerate(request.layers, 1):
        total = sum(layer.atomic_amounts)
        amounts = " ".join(number(v / total) for v in layer.atomic_amounts)
        lines.append(f'{index} "{layer.name}" {number(layer.width_nm * 10)} {number(layer.density_g_cm3)} {amounts}')
    lines.extend(["0 Target layer phases (0=Solid, 1=Gas)",
                  " ".join(str(int(v.phase == "gas")) for v in request.layers),
                  "Target Compound Corrections (Bragg)", " ".join(number(v.compound_correction) for v in request.layers)])
    for key, title in (("displacement_eV", "displacement"), ("lattice_binding_eV", "lattice binding"), ("surface_binding_eV", "surface binding")):
        lines.extend([f"Individual target atom {title} energies (eV)", " ".join(number(getattr(v, key)) for v in request.elements)])
    lines.extend(["Stopping Power Version", str(request.stopping_power_version)])
    return "\r\n".join(lines) + "\r\n"


def render_particles(request: Request) -> bytes:
    """Return CRLF TRIM.DAT bytes with ten header lines and a final CRLF for request.

    Positions convert nm to Angstrom; event energies remain eV. Empty events
    return empty bytes and must not be installed for modes 1..3.
    """
    if not request.particles:
        return b""
    lines = ["TRIM.DAT generated by agentic_srim", "Explicit external events", "Normalization: one event per record",
             "Event label plus eight numeric fields", "Energy in eV; positions in Angstrom", "Direction contains normalized cosines",
             "No external primary-particle correction is applied", request.title,
             "Event Atom Energy Depth LateralPosition AtomDirection", "Name Z eV X Y Z cosX cosY cosZ"]
    for particle in request.particles:
        values = (particle.energy_eV, *(v * 10 for v in particle.position_nm), *particle.direction)
        lines.append(f"{particle.event:<5} {particle.atomic_number} " + " ".join(number(v) for v in values))
    return ("\r\n".join(lines) + "\r\n").encode("ascii")
